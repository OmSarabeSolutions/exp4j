package net.objecthunter.exp4j;

import net.objecthunter.exp4j.function.Function;
import net.objecthunter.exp4j.operator.Operator;
import org.junit.Test;

import java.util.Random;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;

import static org.junit.Assert.*;

public class BytecodeStrategyTest {

    private static final String[] UNARY_FUNCTIONS = {"sin", "cos", "tan", "cot", "log", "log2", "log10", "log1p",
            "abs", "acos", "asin", "atan", "cbrt", "floor", "sinh", "sqrt", "tanh", "cosh", "ceil", "exp", "expm1",
            "signum", "csc", "sec", "csch", "sech", "coth", "toradian", "todegree"};

    private static final Function AVG3 = new Function("avg3", 3) {
        @Override
        public double apply(double... args) {
            return (args[0] + args[1] + args[2]) / 3;
        }
    };

    private static final Function ANSWER = new Function("answer", 0) {
        @Override
        public double apply(double... args) {
            return 42;
        }
    };

    private static final Function DIFF = new Function("diff", 2) {
        @Override
        public double apply(double... args) {
            return args[0] - args[1];
        }
    };

    private static final Operator FACTORIAL = new Operator("!", 1, true, Operator.PRECEDENCE_POWER + 1) {
        @Override
        public double apply(double... args) {
            double result = 1;
            for (int i = 2; i <= (int) args[0]; i++) {
                result *= i;
            }
            return result;
        }
    };

    private static final Operator GREATER = new Operator(">", 2, true, Operator.PRECEDENCE_ADDITION - 1) {
        @Override
        public double apply(double... args) {
            return args[0] > args[1] ? 1d : 0d;
        }
    };

    private static ExpressionBuilder builder(String expression, EvaluationStrategy strategy) {
        return new ExpressionBuilder(expression)
                .variables("x", "y", "z")
                .functions(AVG3, ANSWER, DIFF)
                .operator(FACTORIAL, GREATER)
                .strategy(strategy);
    }

    private static Expression bytecode(String expression) {
        final Expression e = builder(expression, EvaluationStrategy.BYTECODE).build();
        assertFalse("expected generated bytecode for " + expression, e.program() instanceof CompiledExpression);
        return e;
    }

    private static Expression interpreted(String expression) {
        return builder(expression, EvaluationStrategy.INTERPRETED).build();
    }

    /* evaluates both strategies with the same variables and compares results or exceptions */
    private static void assertMatchesInterpreter(String expression, double x, double y, double z) {
        final Expression b = bytecode(expression).setVariable("x", x).setVariable("y", y).setVariable("z", z);
        final Expression i = interpreted(expression).setVariable("x", x).setVariable("y", y).setVariable("z", z);
        Object expected;
        try {
            expected = i.evaluate();
        } catch (RuntimeException ex) {
            expected = ex.getClass().getName() + ": " + ex.getMessage();
        }
        Object actual;
        try {
            actual = b.evaluate();
        } catch (RuntimeException ex) {
            actual = ex.getClass().getName() + ": " + ex.getMessage();
        }
        assertEquals(expression + " with x=" + x + ", y=" + y + ", z=" + z, expected, actual);
    }

    @Test
    public void testDefaultIsInterpreted() {
        assertTrue(new ExpressionBuilder("1+2").build().program() instanceof CompiledExpression);
    }

    @Test(expected = IllegalArgumentException.class)
    public void testNullStrategy() {
        new ExpressionBuilder("1").strategy(null);
    }

    @Test
    public void testBuiltinsMatchInterpreter() {
        final Random rnd = new Random(42);
        final double[] specials = {0d, -0d, 1d, -1d, 0.5, Math.PI, Math.PI / 2, Double.NaN,
                Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY};
        for (String f : UNARY_FUNCTIONS) {
            for (double v : specials) {
                assertMatchesInterpreter(f + "(x)", v, 0, 0);
            }
            for (int k = 0; k < 20; k++) {
                assertMatchesInterpreter(f + "(x)", (rnd.nextDouble() - 0.5) * 10, 0, 0);
            }
        }
        final String[] binary = {"x+y", "x-y", "x*y", "x/y", "x^y", "x%y", "pow(x,y)", "-x", "+x",
                "-x^-y", "x--y", "2x", "x(y)"};
        for (String e : binary) {
            for (double a : specials) {
                for (double b : specials) {
                    assertMatchesInterpreter(e, a, b, 0);
                }
            }
        }
    }

    @Test
    public void testComplexExpressions() {
        final String[] expressions = {
                "log(x) - y * (sqrt(x^cos(y)))",
                "x * y * z + x / y - z % 3 + 2 ^ 3 ^ 2",
                "sin(x)^2 + cos(x)^2",
                "pi * e * φ * π + x",
                "avg3(x, y, z) + answer() * diff(x, z)",
                "x! + 3! > y",
                "avg3(avg3(x, 1, 2), diff(y, z), sin(answer()))",
                "-(-(-x))",
                "x + x + x + x + y * y * y",
                "1/0",
                "1 % 0",
                "cot(0)",
        };
        final Random rnd = new Random(7);
        for (String e : expressions) {
            for (int k = 0; k < 50; k++) {
                assertMatchesInterpreter(e, rnd.nextDouble() * 10, rnd.nextDouble() * 10 - 5, rnd.nextDouble());
            }
        }
    }

    @Test
    public void testVariableNotSet() {
        final Expression e = bytecode("x + y");
        e.setVariable("x", 1);
        try {
            e.evaluate();
            fail();
        } catch (IllegalArgumentException ex) {
            assertEquals("No value has been set for the setVariable 'y'.", ex.getMessage());
        }
        e.setVariable("y", 2);
        assertEquals(3d, e.evaluate(), 0d);
        e.clearVariables();
        try {
            e.evaluate();
            fail();
        } catch (IllegalArgumentException ex) {
            assertEquals("No value has been set for the setVariable 'x'.", ex.getMessage());
        }
    }

    @Test
    public void testNonInternedVariableNames() {
        for (EvaluationStrategy s : EvaluationStrategy.values()) {
            final Expression e = builder("x - y", s).build();
            e.setVariable(new String("x"), 5).setVariable(new StringBuilder("y").toString(), 2);
            assertEquals(3d, e.evaluate(), 0d);
            try {
                e.setVariable(new String("sin"), 1);
                fail();
            } catch (IllegalArgumentException ex) {
                assertTrue(ex.getMessage().contains("'sin' is invalid"));
            }
        }
    }

    @Test
    public void testClearedConstant() {
        final Expression e = bytecode("pi * 2");
        assertEquals(2 * Math.PI, e.evaluate(), 0d);
        e.clearVariables();
        try {
            e.evaluate();
            fail();
        } catch (IllegalArgumentException ex) {
            assertEquals("No value has been set for the setVariable 'pi'.", ex.getMessage());
        }
    }

    @Test
    public void testCopyKeepsBytecodeAndIsIndependent() {
        final Expression e = bytecode("x * 2").setVariable("x", 3);
        final Expression copy = new Expression(e);
        org.junit.Assert.assertSame(e.program(), copy.program());
        copy.setVariable("x", 5);
        assertEquals(6d, e.evaluate(), 0d);
        assertEquals(10d, copy.evaluate(), 0d);
    }

    @Test
    public void testInvalidExpressionKeepsInterpreterErrors() {
        final Expression e = new ExpressionBuilder("1 + ").strategy(EvaluationStrategy.BYTECODE).build();
        assertNull(e.program());
        try {
            e.evaluate();
            fail();
        } catch (IllegalArgumentException ex) {
            assertEquals("Invalid number of operands available for '+' operator", ex.getMessage());
        }
    }

    @Test
    public void testConcurrentEvaluation() throws Exception {
        final ExecutorService executor = Executors.newFixedThreadPool(8);
        try {
            final Expression shared = bytecode("x * y + sin(z)");
            final Future<?>[] futures = new Future<?>[8];
            for (int t = 0; t < futures.length; t++) {
                final int seed = t;
                futures[t] = executor.submit(() -> {
                    final Expression e = new Expression(shared);
                    final Random rnd = new Random(seed);
                    for (int k = 0; k < 10_000; k++) {
                        final double x = rnd.nextDouble(), y = rnd.nextDouble(), z = rnd.nextDouble();
                        e.setVariable("x", x).setVariable("y", y).setVariable("z", z);
                        assertEquals(x * y + Math.sin(z), e.evaluate(), 0d);
                    }
                });
            }
            for (Future<?> f : futures) {
                f.get();
            }
        } finally {
            executor.shutdown();
        }
    }
}
